package main

import (
	"fmt"
	"os"
	"text/template"
)

const codesTemplate = `// Code generated by bankcodes. DO NOT EDIT.

{{ .GoGenerate }}
package goleto

var BankingCodes = []string{
{{- range $code := .Codes }}
	"{{ $code }}",
{{- end }}
}
`

func main() {
	dest := os.Args[1]

	f, err := os.Create(dest)
	if err != nil {
		panic(fmt.Errorf("create file %s: %w", dest, err))
	}

	defer f.Close()

	codes, err := codes()

	if err != nil {
		panic(err)
	}

	t, err := template.New("master").Parse(codesTemplate)
	if err != nil {
		panic(err)
	}

	t.Execute(f, struct {
		Codes      []string
		GoGenerate string
	}{
		Codes:      codes,
		GoGenerate: fmt.Sprintf("//go:generate go run ./cmd/bankcodes %s", dest),
	})
}
